from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from agal.config import load_config
from agal.skills import (
    _prune_empty_parents,
    load_global_state,
    load_local_state,
    save_global_state,
    save_local_state,
)
from agal.sources import get_all_hooks


def _read_json(path: Path) -> dict[str, Any] | None:
    if not path.is_file():
        return {}
    try:
        with open(path, "r", encoding="utf-8") as f:
            data = json.load(f)
    except Exception:
        return None
    return data if isinstance(data, dict) else None


def _write_json(path: Path, data: dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        json.dump(data, f, indent=2)


def _install_claude_adapter(
    source: str, source_dir: Path, target: Path, adapter: dict[str, str]
) -> dict[str, str] | None:
    path = target / ".claude" / "settings.local.json"
    created = not path.exists()
    settings = _read_json(path)
    if settings is None:
        print(f"⚠️  Hook bundle '{source}': cannot read {path.relative_to(target)}, skipping claude adapter.")
        return None

    marketplaces = settings.setdefault("extraKnownMarketplaces", {})
    enabled = settings.setdefault("enabledPlugins", {})
    if not isinstance(marketplaces, dict) or not isinstance(enabled, dict):
        print(f"⚠️  Hook bundle '{source}': {path.relative_to(target)} has an unexpected shape, skipping claude adapter.")
        return None

    marketplace = adapter["marketplace"]
    plugin = adapter["plugin"]
    plugin_key = f"{plugin}@{marketplace}"
    for key, value in enabled.items():
        if value is True and key.startswith(f"{plugin}@") and key != plugin_key:
            print(
                f"⚠️  Hook bundle '{source}': plugin '{plugin}' is already enabled from "
                f"{key.split('@', 1)[1]} (it will load twice)."
            )
    marketplaces[marketplace] = {
        "source": {"source": "directory", "path": str(source_dir)}
    }
    enabled[plugin_key] = True
    _write_json(path, settings)

    if created:
        gitignore = target / ".gitignore"
        if gitignore.is_file() and ".claude/settings.local.json" not in gitignore.read_text(
            encoding="utf-8"
        ):
            print(
                "ℹ️  Add .claude/settings.local.json to .gitignore: "
                "it holds this machine's plugin paths."
            )
    return {"marketplace": marketplace, "plugin": plugin}


def _uninstall_claude_adapter(target: Path, adapter: dict[str, str]) -> bool:
    path = target / ".claude" / "settings.local.json"
    settings = _read_json(path)
    if settings is None:
        return False

    marketplace = adapter.get("marketplace", "")
    plugin = adapter.get("plugin", "")
    plugin_key = f"{plugin}@{marketplace}"
    changed = False
    enabled = settings.get("enabledPlugins")
    if isinstance(enabled, dict):
        if enabled.pop(plugin_key, None) is not None:
            changed = True
        if not enabled:
            settings.pop("enabledPlugins", None)

    marketplaces = settings.get("extraKnownMarketplaces")
    if isinstance(marketplaces, dict) and marketplace in marketplaces:
        still_used = isinstance(enabled, dict) and any(
            key.endswith(f"@{marketplace}") for key in enabled
        )
        if not still_used:
            del marketplaces[marketplace]
            changed = True
        if not marketplaces:
            settings.pop("extraKnownMarketplaces", None)

    if not settings:
        path.unlink(missing_ok=True)
    elif changed:
        _write_json(path, settings)
    return changed


def _opencode_stub_comment(source: str) -> str:
    return f"// Generated by agal from source {source}. Do not edit."


def _install_opencode_adapter(source: str, target: Path, entry: str) -> str | None:
    rel = Path(".opencode") / "plugins" / f"agal-{source}.js"
    path = target / rel
    if path.exists():
        try:
            current = path.read_text(encoding="utf-8")
        except OSError:
            current = ""
        if not current.startswith(_opencode_stub_comment(source)):
            print(
                f"⚠️  Hook bundle '{source}': {rel.as_posix()} exists and was not "
                "written by agal; leaving it unchanged."
            )
            return None

    literal = json.dumps(entry)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        f"{_opencode_stub_comment(source)}\n"
        f"export * from {literal}\n"
        f"export {{ default }} from {literal}\n",
        encoding="utf-8",
    )
    return rel.as_posix()


def _uninstall_opencode_adapter(target: Path, rel: str) -> bool:
    path = target / rel
    if not (path.is_symlink() or path.exists()):
        return False
    path.unlink(missing_ok=True)
    _prune_empty_parents(path.parent, target)
    return True


def _install_agy_adapter(
    source: str,
    target: Path,
    hooks_file: Path,
    previous: dict[str, Any] | None,
) -> list[str] | None:
    path = target / ".agents" / "hooks.json"
    data = _read_json(path)
    if data is None:
        print(f"⚠️  Hook bundle '{source}': cannot read {path.relative_to(target)}, skipping agy adapter.")
        return None
    try:
        source_hooks = json.loads(hooks_file.read_text(encoding="utf-8"))
    except Exception:
        print(f"⚠️  Hook bundle '{source}': cannot read {hooks_file}, skipping agy adapter.")
        return None
    if not isinstance(source_hooks, dict):
        return None

    recorded = set(previous.get("agy", [])) if previous else set()
    installed: list[str] = []
    for hook_name, hook in source_hooks.items():
        key = f"agal-{source}-{hook_name}"
        if key in data and key not in recorded:
            print(f"⚠️  Hook bundle '{source}': hook '{key}' exists and was not written by agal; skipping it.")
            continue
        data[key] = hook
        installed.append(key)

    if installed:
        _write_json(path, data)
    return installed


def _uninstall_agy_adapter(target: Path, keys: list[str]) -> bool:
    path = target / ".agents" / "hooks.json"
    data = _read_json(path)
    if data is None:
        return False
    changed = False
    for key in keys:
        if key in data:
            del data[key]
            changed = True
    if not data:
        path.unlink(missing_ok=True)
    elif changed:
        _write_json(path, data)
    return changed


def _install_adapter(
    runtime: str,
    source: str,
    target: Path,
    hook_info: dict[str, Any],
    previous: dict[str, Any] | None,
) -> Any | None:
    adapter = hook_info["adapters"][runtime]
    if runtime == "claude":
        return _install_claude_adapter(
            source, Path(hook_info["path"]).resolve(), target, adapter
        )
    if runtime == "opencode":
        return _install_opencode_adapter(source, target, adapter)
    if runtime == "agy":
        return _install_agy_adapter(source, target, Path(adapter), previous)
    return None


def _uninstall_adapter(runtime: str, target: Path, value: Any) -> bool:
    if runtime == "claude":
        return _uninstall_claude_adapter(target, value)
    if runtime == "opencode":
        return _uninstall_opencode_adapter(target, value)
    if runtime == "agy":
        return _uninstall_agy_adapter(target, value)
    return False


def install_hook(
    hook_name: str,
    target_dir: Path | None = None,
    scope: str = "local",
    cfg: dict[str, Any] | None = None,
    all_hooks: dict[str, dict[str, Any]] | None = None,
) -> dict[str, Any]:
    """Activate a hook bundle's adapters in the project's selected runtimes."""
    if scope == "global":
        raise ValueError(
            "Global hook installation is not supported; install hooks per project."
        )
    if scope != "local":
        raise ValueError(f"Invalid scope: {scope}. Must be 'local' or 'global'.")
    if cfg is None:
        cfg = load_config()

    if all_hooks is None:
        all_hooks = get_all_hooks(cfg)
    if hook_name not in all_hooks:
        raise ValueError(f"Hook '{hook_name}' not found in any registered source.")

    hook_info = all_hooks[hook_name]
    target = (target_dir or Path.cwd()).resolve()
    state = load_local_state(target)
    runtimes = state.get("runtimes") or ["claude"]
    previous = state.get("hooks", {}).get(hook_name)

    installed: dict[str, Any] = {}
    for runtime in runtimes:
        if runtime not in hook_info.get("adapters", {}):
            print(f"⚠️  Hook bundle '{hook_name}' has no {runtime} adapter")
            continue
        result = _install_adapter(runtime, hook_name, target, hook_info, previous)
        if result is not None:
            installed[runtime] = result

    if any(runtime in installed for runtime in ("claude", "opencode")):
        print(
            f"ℹ️  Hook bundle '{hook_name}' also loads its own skills and commands; "
            "skills agal already copied may appear twice."
        )

    if installed:
        state.setdefault("hooks", {})[hook_name] = {
            "source": hook_info.get("source", "unknown"),
            "adapters": installed,
        }
        save_local_state(target, state)

    return {
        "hook": hook_name,
        "source": hook_info.get("source", "unknown"),
        "scope": scope,
        "adapters": installed,
    }


def uninstall_hook(
    hook_name: str,
    target_dir: Path | None = None,
    scope: str = "local",
) -> bool:
    """Remove a hook bundle's adapters, or a legacy copied hook file."""
    target = (target_dir or Path.cwd()).resolve()

    if scope == "local":
        state = load_local_state(target)
        entry = state.get("hooks", {}).get(hook_name)
        removed = False

        if entry and "adapters" in entry:
            for runtime, value in entry["adapters"].items():
                if _uninstall_adapter(runtime, target, value):
                    removed = True
        else:
            if entry and "path" in entry:
                legacy = Path(entry["path"])
                if not legacy.is_absolute():
                    legacy = target / legacy
            else:
                legacy = target / ".claude" / "hooks" / hook_name
            if legacy.is_symlink() or legacy.exists():
                legacy.unlink(missing_ok=True)
                removed = True

        if entry is not None:
            del state["hooks"][hook_name]
            save_local_state(target, state)
            removed = True
        return removed

    if scope == "global":
        state = load_global_state()
        entry = state.get("hooks", {}).get(hook_name)
        legacy = Path.home() / ".claude" / "hooks" / hook_name
        if entry and entry.get("path"):
            legacy = Path(entry["path"])
        removed = legacy.is_symlink() or legacy.exists()
        legacy.unlink(missing_ok=True)

        if entry is not None:
            del state["hooks"][hook_name]
            save_global_state(state)
            removed = True
        return removed

    raise ValueError(f"Invalid scope: {scope}. Must be 'local' or 'global'.")


def sync_installed_hooks(target_dir: Path, cfg: dict[str, Any] | None = None) -> None:
    """Add or remove hook adapters after the project's runtimes change."""
    target = target_dir.resolve()
    state = load_local_state(target)
    entries = state.get("hooks", {})
    if not entries:
        return
    if cfg is None:
        cfg = load_config()

    all_hooks = get_all_hooks(cfg)
    runtimes = state.get("runtimes") or ["claude"]
    changed = False

    for hook_name, entry in list(entries.items()):
        if "adapters" not in entry:
            continue
        hook_info = all_hooks.get(hook_name)
        if hook_info is None:
            print(f"⚠️  Hook bundle '{hook_name}' is no longer in any source.")
            continue
        adapters = dict(entry["adapters"])
        for runtime in list(adapters):
            if runtime not in runtimes:
                _uninstall_adapter(runtime, target, adapters.pop(runtime))
                changed = True
        for runtime in runtimes:
            if runtime in adapters:
                continue
            if runtime not in hook_info.get("adapters", {}):
                print(f"⚠️  Hook bundle '{hook_name}' has no {runtime} adapter")
                continue
            result = _install_adapter(runtime, hook_name, target, hook_info, entry)
            if result is not None:
                adapters[runtime] = result
                changed = True
        if adapters != entry["adapters"]:
            entry["adapters"] = adapters
            changed = True

    if changed:
        save_local_state(target, state)
